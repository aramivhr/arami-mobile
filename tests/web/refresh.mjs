/** Source of a top-level declaration starting at `start`, by brace matching. */
function take(src, start) {
  const i = src.indexOf(start);
  if (i < 0) throw new Error(`not found: ${start}`);
  let depth = 0, seen = false;
  for (let j = i; j < src.length; j++) {
    if (src[j] === "{") { depth++; seen = true; }
    if (src[j] === "}") { depth--; if (seen && depth === 0) return src.slice(i, j + 1 + (src[j + 1] === ";" ? 1 : 0)); }
  }
  throw new Error(`unbalanced: ${start}`);
}

/** A top-level function by its closing brace at column 0 (safe with object return types). */
function takeBlock(src, start) {
  const i = src.indexOf(start);
  if (i < 0) throw new Error(`not found: ${start}`);
  const j = src.indexOf("\n}\n", i);
  return src.slice(i, j + 2);
}

/**
 * Changes Gevorg still has to paste into Lovable (lovable-prompt-nov13-app-changes.md),
 * applied to the copy only while the website still has the old code, so the tests
 * check the code the prompt asks for. Once Lovable applies them this does nothing.
 */
function pendingDispatch(src) {
  let out = src;
  let note = "";
  if (out.includes('.upsert(notifRows, { onConflict: "dedupe_key", ignoreDuplicates: true })')) {
    const fixed = readFileSync(new URL("./pending/stepMessages.ts", import.meta.url), "utf8");
    const i = out.indexOf("async function stepMessages(");
    const j = out.indexOf("\n}\n", i) + 3;
    out = out.slice(0, i) + fixed.slice(fixed.indexOf("async function stepMessages(")).trimEnd() + "\n" + out.slice(j);
    note += "// Step A patched with tests/web/pending/stepMessages.ts until Lovable applies it.\n";
  }
  const insp = out.indexOf('source: "inspection", source_id: i.id, setting: "inspection_due"');
  if (insp >= 0) {
    const start = out.lastIndexOf("  try {", insp);
    const end = out.indexOf("\n\n", insp);
    out = out.slice(0, start) + "  // Inspection-due alerts stopped (Gevorg, 2026-11-13).\n" + out.slice(end + 2);
    note += "// Inspection-due pushes removed until Lovable applies it.\n";
  }
  return note + out;
}

